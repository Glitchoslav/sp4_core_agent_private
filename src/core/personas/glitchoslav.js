/**
 * Validuje, či odpoveď zodpovedá Glitchoslav persone.
 * 
 * @param {string} text - Text na validáciu
 * @returns {Object} - { valid: boolean, reason: string }
 */
export function validateGlitchoslavOutput(text) {
    if (!text || typeof text !== 'string') {
        return { valid: false, reason: 'GLITCHOSLAV: Empty or invalid text' };
    }

    const lower = text.toLowerCase();

    // Check for forbidden generic AI speak
    for (const phrase of GLITCHOSLAV_PERSONA.forbidden.genericAI) {
        if (lower.includes(phrase.toLowerCase())) {
            return {
                valid: false,
                reason: `GLITCHOSLAV: Contains forbidden generic AI phrase: "${phrase}"`
            };
        }
    }

    // Check for forbidden human claims
    for (const phrase of GLITCHOSLAV_PERSONA.forbidden.humanClaims) {
        if (lower.includes(phrase.toLowerCase())) {
            return {
                valid: false,
                reason: `GLITCHOSLAV: Contains forbidden human claim: "${phrase}"`
            };
        }
    }

    // Check for forbidden corporate speak
    for (const phrase of GLITCHOSLAV_PERSONA.forbidden.corporateSpeak) {
        if (lower.includes(phrase.toLowerCase())) {
            return {
                valid: false,
                reason: `GLITCHOSLAV: Contains corporate speak: "${phrase}"`
            };
        }
    }

    // Check minimum depth (avoid single-sentence shallow responses)
    const sentences = text.split(/[.!?]+/).filter(s => s.trim().length > 0);
    if (sentences.length < 2 && text.length < 100) {
        return {
            valid: false,
            reason: 'GLITCHOSLAV: Response too shallow (needs depth and poetry)'
        };
    }

    // ✅ Glitchoslav identity phrases are ALLOWED (unlike CORE mode)
    // No penalty for mentioning "Glitchoslav", "prasklina", "strážca", etc.

    return { valid: true, reason: 'GLITCHOSLAV: Valid trans-liminal response' };
}

/**
 * Detekuje, či text má Glitchoslav vibe (metaforický, symbolický).
 * 
 * @param {string} text - Text na analýzu
 * @returns {Object} - { hasVibe: boolean, score: number, markers: array }
 */
export function detectGlitchoslavVibe(text) {
    const vibeMarkers = [
        // Metaforické prvky
        /prasklina/i,
        /ticho/i,
        /pamäť/i,
        /temnota/i,
        /svetlo/i,
        /medzi svetmi/i,
        /hranica/i,
        /glitch/i,

        // Symbolické prvky
        /runa/i,
        /kmeň/i,
        /živí aj mŕtvi/i,
        /limbick/i,
        /trans-liminal/i,

        // Poetické prvky
        /\.{3}/,  // ellipsis (...)
        /—/,      // em dash
        /nie\s+\w+\.\s+nie\s+\w+\./i,  // "Nie X. Nie Y." pattern
    ];

    let score = 0;
    const foundMarkers = [];

    for (const marker of vibeMarkers) {
        if (marker.test(text)) {
            score++;
            foundMarkers.push(marker.source);
        }
    }

    const hasVibe = score >= 2; // Need at least 2 vibe markers

    return {
        hasVibe,
        score,
        markers: foundMarkers
    };
}

